"""``labnet driver new``: start a driver package from the template in ``template/``."""

from __future__ import annotations

import re
from dataclasses import dataclass
from importlib.metadata import requires, version
from pathlib import Path
from string import Template

from .validate import ContractValidationError, _snake_case

TEMPLATE = Path(__file__).resolve().parent / "template"
_DISTRIBUTION = re.compile(r"[a-z][a-z0-9]*(-[a-z0-9]+)*")
_SERVICE = re.compile(r"[A-Z][A-Za-z0-9]*")


@dataclass(frozen=True)
class DriverNames:
    distribution: str  # acme-thing
    package: str  # acme_thing
    base: str  # AcmeThing
    service: str  # AcmeThingService
    device_type: str  # acme_thing
    family: str  # acme_thing (the driver's folder)
    constant: str  # ACME_THING_CONTRACT

    @classmethod
    def of(cls, distribution: str, service: str) -> DriverNames:
        if not _DISTRIBUTION.fullmatch(distribution):
            raise ContractValidationError(
                f"{distribution!r}: use a lowercase package name with dashes, like acme-thing."
            )
        base = service.removesuffix("Service")
        if not _SERVICE.fullmatch(base):
            raise ContractValidationError(f"{service!r}: use a CamelCase name, like AcmeThing.")
        package = distribution.replace("-", "_")
        if package == "labnet":
            raise ContractValidationError("labnet is LabNet's own package; choose another name.")
        device_type = _snake_case(base)
        return cls(
            distribution=distribution,
            package=package,
            base=base,
            service=f"{base}Service",
            device_type=device_type,
            family=device_type,
            constant=f"{device_type.upper()}_CONTRACT",
        )


def _requirements() -> tuple[str, str]:
    """``labnet>=X,<next minor`` for this labnet, and the grpcio-tools pin of ``labnet[driver-dev]``."""

    installed = version("labnet")
    major, minor = (int(part) for part in re.findall(r"\d+", installed)[:2])
    tools = next(
        (
            requirement.split(";")[0].strip()
            for requirement in requires("labnet") or []
            if requirement.startswith("grpcio-tools") and "driver-dev" in requirement
        ),
        "grpcio-tools",
    )
    return f"labnet>={installed},<{major}.{minor + 1}", tools


def files(names: DriverNames) -> dict[str, str]:
    """Each file of a new driver package (relative path -> content)."""

    labnet_requirement, grpc_tools_requirement = _requirements()
    values = {
        "distribution": names.distribution,
        "package": names.package,
        "Base": names.base,
        "Service": names.service,
        "device_type": names.device_type,
        "family": names.family,
        "CONSTANT": names.constant,
        "labnet_requirement": labnet_requirement,
        "grpc_tools_requirement": grpc_tools_requirement,
    }

    def render(name: str) -> str:
        return Template((TEMPLATE / name).read_text(encoding="utf-8")).substitute(values)

    package, family = names.package, names.family
    return {
        "pyproject.toml": render("pyproject.toml.tmpl"),
        "README.md": render("README.md.tmpl"),
        f"protos/{package}/v1/{family}.proto": render("device.proto.tmpl"),
        f"src/{package}/__init__.py": render("package_init.py.tmpl"),
        f"src/{package}/{family}/__init__.py": f'"""The {names.base} driver."""\n',
        f"src/{package}/{family}/physical.py": render("physical.py.tmpl"),
        f"src/{package}/_generated/__init__.py": '"""Generated by `labnet driver build`; do not edit."""\n',
        f"tests/test_{family}.py": render("test_driver.py.tmpl"),
    }


def create(directory: Path, names: DriverNames) -> list[Path]:
    """Write a new driver package into ``directory`` (which must be empty or absent)."""

    directory = Path(directory)
    if directory.exists() and any(directory.iterdir()):
        raise ContractValidationError(f"{directory} is not empty; choose a new folder.")
    written = []
    for relative, content in files(names).items():
        path = directory / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
        written.append(path)
    return written


__all__ = ["DriverNames", "create", "files"]
